use super::Toolbox;
use crate::ui::theme;
use gpui_kit::*;
impl Render for Toolbox {
    fn render(&mut self, window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        ely::primitives::FocusScope::new(&self.focus)
            .root()
            .flex()
            .flex_col()
            .size_full()
            .font_weight(theme::FONT_WEIGHT)
            .text_size(px(theme::BODY_SIZE))
            .font_family(
                gpui_kit::component::theme::Theme::global(cx)
                    .font_family
                    .clone(),
            )
            .text_color(rgb(theme::INK))
            .child(super::title_bar::title_bar(window))
            .child(
                div()
                    .flex()
                    .flex_1()
                    .min_h_0()
                    .w_full()
                    .rounded_b(super::title_bar::window_radius(window))
                    .bg(rgb(theme::BACKGROUND))
                    .child(
                        div()
                            .flex_shrink_0()
                            .h_full()
                            .rounded_bl(super::title_bar::window_radius(window))
                            .overflow_hidden()
                            .child(self.sidebar(window, cx)),
                    )
                    .child(
                        div()
                            .id("workspace")
                            .flex()
                            .flex_col()
                            .flex_1()
                            .min_w_0()
                            .min_h_0()
                            .h_full()
                            .overflow_y_scroll()
                            .pt(px(theme::CONTENT_TOP))
                            .px(px(theme::CONTENT_HORIZONTAL))
                            .pb_4()
                            .gap(px(theme::CONTENT_GAP))
                            .child(
                                div()
                                    .flex()
                                    .flex_col()
                                    .flex_shrink_0()
                                    .gap_2()
                                    .child(
                                        div()
                                            .text_size(px(theme::TITLE_SIZE))
                                            .font_weight(theme::FONT_WEIGHT)
                                            .child(self.tool.title()),
                                    )
                                    .child(
                                        div()
                                            .text_size(px(theme::LABEL_SIZE))
                                            .text_color(theme::muted())
                                            .child(self.tool.description()),
                                    ),
                            )
                            .child(self.page()),
                    ),
            )
    }
}
